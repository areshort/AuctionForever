"""Build addon/AuctionForever/Suffixes.lua: random-suffix names by bonus list, from WoW Forever's own tables.

Source: wago.tools product "wowf" DB2 tables exported as CSV (named <Table>_<build>.csv):
  ItemBonus            bonus list -> bonuses; Type 5 = the name suffix (Value_0 = an ItemNameDescription ID)
  ItemNameDescription  ID -> "of the Whale", "of the Bear", ...
The auction API gives a suffix item's version as its bonus list (item.bonus_lists, e.g. 12719 = "of the Whale"), the
same ID the item's link carries; the add-on and the collector key suffix versions by it.

Run: python -I tools/build_suffixes.py <data dir> [build]
"""
import csv, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'addon', 'AuctionForever', 'Suffixes.lua')


def read(data, table, build):
    with open(os.path.join(data, f'{table}_{build}.csv'), encoding='utf-8', newline='') as f:
        return list(csv.DictReader(f))


def main():
    data = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'data')
    build = sys.argv[2] if len(sys.argv) > 2 else '1.60.1.71037'
    desc = {int(r['ID']): r['Description_lang'] for r in read(data, 'ItemNameDescription', build)}
    names = {}
    for r in read(data, 'ItemBonus', build):
        if r['Type'] == '5':
            n = desc.get(int(r['Value_0']))
            if n:
                names[int(r['ParentItemBonusListID'])] = n
    bad = [n for n in names.values() if any(ord(c) > 127 for c in n) or '"' in n or '\\' in n]
    if bad:
        sys.exit(f'non-ASCII or quote in suffix names: {bad[:5]}')
    rows = ','.join(f'[{k}]="{v}"' for k, v in sorted(names.items()))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('-- Generated by tools/build_suffixes.py from WoW Forever ' + build + ' (ItemBonus + ItemNameDescription). Do not edit.\n')
        f.write('-- Random-suffix names by bonus list (the ID in an item link and in the auction data): AF_Suffix[12719] = "of the Whale".\n')
        f.write('AF_SuffixBuild = "' + build + '"\n')
        f.write('AF_Suffix = {' + rows + '}\n')
    print(f'{len(names)} suffix bonus lists -> {OUT}')


if __name__ == '__main__':
    main()
